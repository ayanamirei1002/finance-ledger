/* -------- 发票 --------
 * 第 1 行：与流水完全一致                          → 完全匹配
 * 第 2 行：日期差 1 天                            → 完全匹配（容差内）
 * 第 3 行：金额比流水多 40 元                      → 疑似匹配 + 金额不一致异常
 * 第 4 行：名称是变体「广州戊己贸易公司」            → 完全匹配（归一化后一致）
 * 第 5 行：流水里没有对应记录（杭州那笔没有发票）      → 有发票无流水
 */
const invoices = [
  { 开票日期: '2026-09-01', 销售方名称: '上海某某科技有限公司', 价税合计: 1130.0, 发票号码: '12345678' },
  { 开票日期: '2026-09-06', 销售方名称: '北京甲乙文化传播有限公司', 价税合计: 5000.0, 发票号码: '23456789' },
  { 开票日期: '2026-09-10', 销售方名称: '深圳丙丁物流有限公司', 价税合计: 900.5, 发票号码: '34567890' },
  { 开票日期: '2026-09-14', 销售方名称: '广州戊己贸易公司', 价税合计: 2300.0, 发票号码: '45678901' },
  { 开票日期: '2026-09-22', 销售方名称: '某某管理咨询有限公司', 价税合计: 3000.0, 发票号码: '56789012' },
];

/* -------- 收据 -------- */
const receipts = [
  { 日期: '2026-09-25', 收款单位: '顺丰速运有限公司', 金额: 45.0, 备注: '快递费收据' },
];

/* -------- 写出 -------- */
const fs = require('fs');
fs.mkdirSync(OUT_DIR, { recursive: true });

const files = [
  ['付款流水.xlsx', '流水', transactions],
  ['发票明细.xlsx', '发票', invoices],
  ['收据明细.xlsx', '收据', receipts],
];

for (const [filename, sheetName, rows] of files) {
  const ws = XLSX.utils.json_to_sheet(rows);
  // 设置列宽，便于人工查看
  const cols = Object.keys(rows[0]).map((k) => ({ wch: Math.max(12, k.length * 2 + 6) }));
  ws['!cols'] = cols;
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, sheetName);
  const file = path.join(OUT_DIR, filename);
  XLSX.writeFile(wb, file);
  console.log('已生成:', filename, `(${rows.length} 行)`);
}

